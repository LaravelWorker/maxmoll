<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих данных при обновлении (редактировании) существующего заказа.
 * Поддерживает частичное обновление полей, что позволяет изменять только переданные параметры.
 */
class UpdateOrderRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая редактирование заказа без дополнительных проверок прав доступа.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса на обновление заказа.
     *
     * @return array Ассоциативный массив с правилами валидации для полей заказа.
     */
    public function rules(): array
    {
        return [
            // Идентификатор клиента: правило 'sometimes' применяет проверки, только если поле передано в запросе.
            // Если передано, то оно не может быть пустым ('required') и клиент должен существовать в базе.
            'customer_id'        => ['sometimes', 'required', 'integer', 'exists:customers,id'],
            
            // Идентификатор склада: проверяется на существование в базе только при наличии в запросе.
            'warehouse_id'       => ['sometimes', 'required', 'integer', 'exists:warehouses,id'],
            
            // Список товаров заказа: если передан ('sometimes'), должен быть массивом ('required') и содержать хотя бы 1 элемент.
            'items'              => ['sometimes', 'required', 'array', 'min:1'],
            
            // Правила для каждой товарной позиции (если передан массив items):
            // 'required_with:items' требует обязательного наличия product_id у каждого элемента массива.
            // Также проверяется существование товара и отсутствие дублей (distinct) в рамках текущего запроса.
            'items.*.product_id' => ['required_with:items', 'integer', 'exists:products,id', 'distinct'],
            
            // Количество товара в позиции: обязательно, если передан массив items, должно быть целым числом не меньше 1.
            'items.*.count'      => ['required_with:items', 'integer', 'min:1'],
        ];
    }
}