<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих данных при создании межскладского перемещения.
 * Обеспечивает проверку складов (отправителя и получателя) на предмет их существования 
 * и отличия друг от друга, а также валидацию списка перемещаемых товаров.
 */
class StoreTransferRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая выполнение запроса на перемещение товаров.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса.
     *
     * @return array Ассоциативный массив с правилами валидации для полей перемещения.
     */
    public function rules(): array
    {
        return [
            // Идентификатор склада-отправителя: обязателен, должен существовать в БД.
            // Правило 'different:to_warehouse_id' гарантирует, что нельзя переместить товары на тот же самый склад.
            'from_warehouse_id'  => ['required', 'integer', 'exists:warehouses,id', 'different:to_warehouse_id'],
            
            // Идентификатор склада-получателя: обязателен, должен существовать в БД.
            'to_warehouse_id'    => ['required', 'integer', 'exists:warehouses,id'],
            
            // Список перемещаемых товаров: массив позиций, обязателен, должен содержать минимум одну запись.
            'items'              => ['required', 'array', 'min:1'],
            
            // Правила для каждой товарной позиции:
            // Идентификатор товара: обязателен, должен существовать и не должен дублироваться (distinct) в рамках текущего запроса.
            'items.*.product_id' => ['required', 'integer', 'exists:products,id', 'distinct'],
            
            // Количество товара в позиции: обязательно, должно быть целым числом, минимальное значение 1.
            'items.*.count'      => ['required', 'integer', 'min:1'],
        ];
    }

    /**
     * Кастомные сообщения об ошибках (опционально, для удобства UI).
     */
    public function messages(): array
    {
        return [
            'from_warehouse_id.different' => 'Склад-отправитель и склад-получатель не могут совпадать.',
            'items.required'              => 'Необходимо указать хотя бы один товар для перемещения.',
            'items.*.count.min'           => 'Количество товара должно быть больше нуля.',
        ];
    }
}