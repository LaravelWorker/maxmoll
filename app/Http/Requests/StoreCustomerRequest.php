<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих данных при создании нового покупателя (клиента).
 * Обеспечивает проверку обязательных полей и форматов контактных данных.
 */
class StoreCustomerRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая создание клиента без дополнительных проверок прав доступа.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса на создание.
     *
     * @return array Ассоциативный массив с правилами валидации для полей клиента.
     */
    public function rules(): array
    {
        return [
            // Имя клиента: обязательное поле, строковый тип, ограничение длины в 255 символов
            'name'  => ['required', 'string', 'max:255'],
            
            // Номер телефона: необязательное поле, строковый тип, ограничение длины в 255 символов
            'phone' => ['nullable', 'string', 'max:255'],
            
            // Электронная почта: необязательное поле, проверка на валидный формат email, ограничение длины
            'email' => ['nullable', 'email', 'max:255'],
        ];
    }

    public function messages(): array
    {
        return [
            'name.required' => 'Имя покупателя обязательно для заполнения.',
            'email.email'   => 'Введите корректный адрес электронной почты.',
            'email.unique'  => 'Покупатель с таким email уже существует.',
        ];
    }
}