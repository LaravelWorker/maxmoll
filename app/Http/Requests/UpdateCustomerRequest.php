<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих данных при обновлении существующего покупателя (клиента).
 * Поддерживает частичное обновление полей (например, при PATCH-запросах).
 */
class UpdateCustomerRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая обновление данных клиента без дополнительных проверок ролей.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса на обновление.
     *
     * @return array Ассоциативный массив с правилами валидации для полей клиента.
     */
    public function rules(): array
    {
        return [
            // Имя клиента: правило 'sometimes' означает, что поле будет проверяться, 
            // только если оно физически присутствует во входящем запросе.
            // Если оно передано, то обязательно ('required') не должно быть пустым, строка до 255 символов.
            'name'  => ['sometimes', 'required', 'string', 'max:255'],
            
            // Номер телефона: поле может быть пустым (null), если передано — должно быть строкой до 255 символов.
            'phone' => ['nullable', 'string', 'max:255'],
            
            // Электронная почта: поле может быть пустым, если передано — проверяется на валидный формат email.
            'email' => ['nullable', 'email', 'max:255'],
        ];
    }
}