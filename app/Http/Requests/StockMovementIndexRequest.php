<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих параметров при получении истории движений товаров.
 * Обеспечивает проверку фильтров по складу, товару, типу документа и временному периоду.
 */
class StockMovementIndexRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая доступ к фильтрации движений товаров всем пользователям.
     */
    public function authorize(): bool
    {
        // Доступ к просмотру истории движений открыт, дополнительная авторизация не требуется
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса.
     *
     * @return array Ассоциативный массив правил валидации для фильтров истории движений.
     */
    public function rules(): array
    {
        return [
            // Фильтрация по конкретному складу (проверяется реальное существование ID в таблице складов)
            'warehouse_id' => ['nullable', 'integer', 'exists:warehouses,id'],
            
            // Фильтрация по конкретному товару (проверяется реальное существование ID в таблице товаров)
            'product_id'   => ['nullable', 'integer', 'exists:products,id'],
            
            // Фильтрация по типу документа-источника, вызвавшего движение (разрешены только order, supply, transfer)
            'doc_type'     => ['nullable', 'string', 'in:order,supply,transfer'],
            
            // Начальная дата для фильтрации движений по периоду времени
            'date_from'    => ['nullable', 'date'],
            
            // Конечная дата периода (для логической целостности не может быть раньше date_from)
            'date_to'      => ['nullable', 'date', 'after_or_equal:date_from'],
            
            // Количество записей на одну страницу для пагинации (в пределах от 1 до 100)
            'per_page'     => ['nullable', 'integer', 'min:1', 'max:100'],
        ];
    }
}