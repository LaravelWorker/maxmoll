<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих параметров при получении списка поставок.
 * Обеспечивает проверку фильтров (по складу, периоду дат) и настроек пагинации.
 */
class SupplyIndexRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая выполнение запроса на просмотр списка поставок.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса.
     *
     * @return array Ассоциативный массив с правилами валидации для полей фильтрации.
     */
    public function rules(): array
    {
        return [
            // Фильтрация поставок по конкретному складу (указанный ID должен существовать в таблице warehouses)
            'warehouse_id' => ['nullable', 'integer', 'exists:warehouses,id'],
            
            // Начальная дата для фильтрации списка поставок по времени их создания
            'date_from'    => ['nullable', 'date'],
            
            // Конечная дата периода (для сохранения логической целостности не может быть раньше начальной даты date_from)
            'date_to'      => ['nullable', 'date', 'after_or_equal:date_from'],
            
            // Количество записей на одну страницу для пагинации (ограничение выборки от 1 до 100 элементов)
            'per_page'     => ['nullable', 'integer', 'min:1', 'max:100'],
        ];
    }
}