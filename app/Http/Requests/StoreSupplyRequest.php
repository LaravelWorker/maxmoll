<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих данных при создании (оформлении) новой поставки.
 * Обеспечивает проверку обязательных параметров, существования целевого склада и товаров, 
 * а также корректности передаваемого списка товарных позиций (отсутствие дублей, положительное количество).
 */
class StoreSupplyRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая выполнение запроса на создание поставки.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса.
     *
     * @return array Ассоциативный массив с правилами валидации для полей поставки.
     */
    public function rules(): array
    {
        return [
            // Обязательное поле: идентификатор склада, на который приходуется товар (проверка на существование в БД)
            'warehouse_id'       => ['required', 'integer', 'exists:warehouses,id'],
            
            // Обязательное поле: массив позиций поставки. Должен содержать минимум одну запись
            'items'              => ['required', 'array', 'min:1'],
            
            // Правила для каждой товарной позиции:
            // Идентификатор товара обязателен, должен существовать, и не должен повторяться в рамках одной поставки (distinct)
            'items.*.product_id' => ['required', 'integer', 'exists:products,id', 'distinct'],
            
            // Количество приходуемого товара: обязательно, должно быть целым числом не меньше 1
            'items.*.count'      => ['required', 'integer', 'min:1'],
        ];
    }

    /**
     * Получить пользовательские сообщения об ошибках для определенных правил валидации.
     *
     * @return array Ассоциативный массив кастомных сообщений, более понятных для конечного пользователя.
     */
    public function messages(): array
    {
        return [
            // Сообщение при неверном указании склада назначения
            'warehouse_id.exists'         => 'Указанный склад не существует.',
            
            // Сообщение, предотвращающее дублирование одной и той же товарной позиции в списке
            'items.*.product_id.distinct' => 'Товар не должен повторяться в рамках одной поставки.',
            
            // Сообщение при попытке оприходовать несуществующий в базе товар
            'items.*.product_id.exists'   => 'Один из выбранных товаров не существует.',
            
            // Сообщение при указании нулевого или отрицательного количества в позиции
            'items.*.count.min'           => 'Количество товара должно быть не менее 1.',
        ];
    }
}