<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Класс запроса для валидации входящих данных при создании нового заказа.
 * Обеспечивает проверку обязательных полей, существования связанных сущностей 
 * (клиент, склад, товары) и корректности состава заказа (отсутствие дублей позиций).
 */
class StoreOrderRequest extends FormRequest
{
    /**
     * Определить, авторизован ли пользователь для выполнения данного запроса.
     *
     * @return bool Возвращает true, разрешая создание заказа без дополнительных проверок прав доступа.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Получить массив правил валидации, применяемых к параметрам запроса.
     *
     * @return array Ассоциативный массив с правилами валидации для создания заказа.
     */
    public function rules(): array
    {
        return [
            // Обязательное поле, идентификатор покупателя, проверяется реальное существование в базе данных
            'customer_id'       => ['required', 'integer', 'exists:customers,id'],
            
            // Обязательное поле, идентификатор склада, с которого будет отгрузка (существование в БД)
            'warehouse_id'      => ['required', 'integer', 'exists:warehouses,id'],
            
            // Заказ должен содержать массив позиций (товаров), как минимум одну позицию
            'items'             => ['required', 'array', 'min:1'],
            
            // Правила для каждой позиции товара в массиве:
            // Товар обязателен, должен существовать, и ID товара не должен дублироваться (distinct) в рамках одного заказа
            'items.*.product_id'=> ['required', 'integer', 'exists:products,id', 'distinct'],
            
            // Количество для каждой позиции обязательно, должно быть целым числом и не меньше 1
            'items.*.count'     => ['required', 'integer', 'min:1'],
        ];
    }

    /**
     * Получить пользовательские сообщения об ошибках для определенных правил валидации.
     *
     * @return array Ассоциативный массив кастомных сообщений об ошибках, удобных для чтения клиентом.
     */
    public function messages(): array
    {
        return [
            'customer_id.required' => 'Не указан покупатель.',
            'warehouse_id.required' => 'Не указан склад.',
            'items.required' => 'Заказ должен содержать хотя бы одну позицию.',
            // Переопределение стандартных сообщений для ошибок проверки внешних ключей
            'customer_id.exists'         => 'Указанный покупатель не существует.',
            'warehouse_id.exists'        => 'Указанный склад не существует.',
            
            // Переопределение сообщения при попытке добавить один и тот же товар несколько раз в один заказ
            'items.*.product_id.distinct'=> 'Товар не должен повторяться в рамках одного заказа.',
            
            // Сообщение при передаче несуществующего ID товара в массиве позиций
            'items.*.product_id.exists'  => 'Один из выбранных товаров не существует.',
        ];
    }
}